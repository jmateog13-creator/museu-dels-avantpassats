/* =========================================================================
   MUSEU DELS AVANTPASSATS · dades
   -------------------------------------------------------------------------
   Una vitrina = un instrument de l'orquestra = un vídeo que recorre tot el
   seu llinatge. El motor (escena.js) no sap res de trompetes: només llegeix
   això. Afegir el violí és afegir una entrada a INSTRUMENTS.

   Tira de notes possibles:
   `possibles` són semitons per sobre d'una fonamental de referència (Do2,
   MIDI 36). La tira va de 12 a 48 (Do3 → Do6). Les melodies de cada parada
   NOMÉS fan servir notes de `possibles`: el so ensenya què podia tocar
   l'instrument d'aquella època, i la tira s'encén nota a nota mentre sona.
   Els valors són aproximats (afinacions d'època variables) i ho diem així.
   ========================================================================= */

