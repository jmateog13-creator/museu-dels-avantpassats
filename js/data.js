const rang = (a, b) => Array.from({ length: b - a + 1 }, (_, i) => a + i);

// nota de melodia: [temps relatiu (s), semitò sobre la fonamental, durada (s), intensitat 0-1]
const N = (t, s, d, v = 0.8) => ({ t, s, d, v });

// Corda fregada: una nota és a l'abast si és entre la corda més greu a l'aire
// i la més aguda + l'extensió de la mà (que creix quan s'allarga el mànec).
const abast = (cordes, extensio) => rang(cordes[0], cordes[cordes.length - 1] + extensio);
// Escala diatònica de Re (flautes de sis forats) entre dos semitons.
const diatonicaRe = (a, b) => rang(a, b).filter(s => [0, 2, 4, 5, 7, 9, 11].includes(((s - 2) % 12 + 12) % 12));
// Acords: plaqué (tot alhora) i rasguejat (les cordes una rere l'altra, 18 ms).
const acord = (t, notes, d, v = .8) => notes.map(s => N(t, s, d, v));
const rasg = (t, notes, d = .5, v = .8) => notes.map((s, k) => N(t + k * .018, s, d, v));
// Percussió sense altura: `s` és el codi del so (vegeu SONS a mecanica.js) i el ritme es
// descriu com un patró de 16 passos: { codi: [passos] }. `pas` = segons per pas.
const ritme = (pas, pistes, compassos = 1, vel = {}) => {
  const out = [];
  for (let c = 0; c < compassos; c++)
    for (const [codi, passos] of Object.entries(pistes))
      passos.forEach(k => out.push({ ...N((c * 16 + k) * pas, +codi, pas * .9, vel[codi] ?? .8), pas: k }));
  return out.sort((a, b) => a.t - b.t);
};
