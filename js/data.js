// Sèrie harmònica de la trompeta natural, en semitons sobre la fonamental.
// H7, H11 i H13 queden desafinats respecte del temperament: és real i s'ha de sentir.
const HARMONICS = { 2: 12, 3: 19, 4: 24, 5: 28, 6: 31, 7: 33.69, 8: 36, 9: 38, 10: 40, 11: 41.51, 12: 43, 13: 44.41, 14: 45.69, 16: 48 };
const harm = (...hs) => hs.map(h => HARMONICS[h]);
// Sèrie harmònica de la trompa en Fa (fonamental Fa1 = -7).
